"""Inject the D3 v2 report (markdown + figures) into the dashboard between <!--REPORT:BEGIN--> and <!--REPORT:END-->.
One pipeline: analysis JSON -> d3_report_v2.py (verdict table, Nemotron text, structured check, figures) -> this script ->
dashboard. Re-running after new evidence updates the verdicts, the report and the screen together.
Usage: python scripts/build_dashboard_report.py [artifacts/reports/d3_report_v2.md] [dashboard/audit_gate.html]"""
import html, json, re, shutil, sys, os

md_path = sys.argv[1] if len(sys.argv) > 1 else "artifacts/reports/d3_report_v2.md"
page = sys.argv[2] if len(sys.argv) > 2 else "dashboard/audit_gate.html"
md = open(md_path).read(); run = json.load(open(os.path.join(os.path.dirname(md_path), "d3_report_v2_run.json")))

def inline(t):
    t = html.escape(t, quote=False)
    t = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", t); t = re.sub(r"(?<!\*)\*(?!\s)(.+?)\*(?!\*)", r"<i>\1</i>", t)
    return re.sub(r"`([^`]+)`", r'<span class="num">\1</span>', t)

body = md.split("\n---\n", 1)[1] if "\n---\n" in md else md
out, lst = [], False
for line in body.splitlines():
    l = line.rstrip()
    if lst and not l.startswith("- "): out.append("</ul>"); lst = False
    if not l.strip(): continue
    m = re.match(r"!\[(.*?)\]\((figures/[^)]+)\)", l)
    if m: out.append(f'<img class="rep-fig" src="report/{m.group(2)}" alt="{html.escape(m.group(1))}">'); continue
    if l.startswith("## "): out.append(f"<h3>{inline(l[3:].strip())}</h3>"); continue
    if l.startswith("- "):
        if not lst: out.append("<ul>"); lst = True
        out.append(f"<li>{inline(l[2:])}</li>"); continue
    out.append(f"<p>{inline(l.strip())}</p>")
if lst: out.append("</ul>")
meta = (f'<p class="note">Generated by <span class="num">scripts/d3_report_v2.py</span>: verdicts decided by code '
        f'(table hash <span class="num">{run["verdict_hash"][:16]}</span>), prose by Nemotron 3 Super on Token Factory in {run["latency_sec"]} s, '
        f'structured validator findings: <b>{len(run["issues"])}</b>. Figures are drawn by code from the same table.</p>')
block = "<!--REPORT:BEGIN-->\n" + meta + '\n<div class="report">' + "\n".join(out) + "</div>\n<!--REPORT:END-->"
s = open(page).read()
s = re.sub(r"<!--REPORT:BEGIN-->.*?<!--REPORT:END-->", lambda _: block, s, flags=re.S)
open(page, "w").write(s)
os.makedirs("dashboard/report/figures", exist_ok=True)
for f in os.listdir(os.path.join(os.path.dirname(md_path), "figures")):
    shutil.copy(os.path.join(os.path.dirname(md_path), "figures", f), f"dashboard/report/figures/{f}")
print("injected", len(out), "blocks; findings", len(run["issues"]))
